def kv_cache_torch_dtype(ecfg: EngineConfig) -> torch.dtype:
    if ecfg.kv_cache_dtype == "auto":
        return ecfg.dtype
    if ecfg.kv_cache_dtype in ("fp8", "fp8_e4m3"):
        return torch.float8_e4m3fn
    raise ValueError(f"kv_cache_dtype must be auto or fp8, not {ecfg.kv_cache_dtype!r}")


def fp8_e4m3_max(device: torch.device) -> float:
    """Largest finite FP8 E4M3 value on the device (kiln/platform.py, fp8_max: 240 on
    trn1/trn2, 448 on trn3). On CPU torch.float8_e4m3fn is the fn variant (448)."""
    # meta: the capture of a device run (kiln/capture.py), which must trace the device's value.
    if device.type not in ("neuron", "meta"):
        return float(torch.finfo(torch.float8_e4m3fn).max)
    from .. import platform

    return platform.fp8_max(platform.runtime_target())


def neuronx_cc_args(kv_dtype: torch.dtype, fp8_weights: bool = False) -> list[str]:
    """Extra neuronx-cc arguments for every graph.

    trn1/trn2 FP8 is e4m3 with inf (max 240) and torch has no such dtype, so an fp8 KV
    cache or FP8 weights are float8_e4m3fn in the graph, which neuronx-cc rejects there: "[NCC_EVRF051]
    Data type F8E4M3FN is not supported on TRN1/TRN2 ... use the
    --experimental-unsafe-fp8e4m3fn-as-fp8e4m3 flag" (measured on trn1, SDK 2.32). The values
    are clamped to 240 on write, so the cast is exact. libtorch_neuronx_lite injects the flag
    only for trn2 (compile/backend.py, _apply_platform_compiler_args), not trn1. On trn2 /
    trn3 kiln/platform.py adds --logical-nc-config and vllm-neuron's argument set.
    KILN_CC_ARGS appends arguments for experiments (e.g. "-O1"), split the way a shell splits them, so
    one argument can carry spaces when quoted: NxD Inference passes its tensorizer options as one
    `--tensorizer-options='--enable-ccop-compute-overlap --cc-pipeline-tiling-factor=2 ...'`
    (neuronx-distributed-inference models/model_wrapper.py:85-107, 4bcdc54). An unquoted value splits as before.
    """
    from .. import platform

    args = platform.neuronx_cc_args(platform.runtime_target(), fp8=kv_dtype == torch.float8_e4m3fn or fp8_weights)
    extra = os.environ.get("KILN_CC_ARGS")
    if extra:
        args += shlex.split(extra)
    return args


# neuronx-cc refuses a graph past 5M instructions ("[NCC_EBVF030] Instructions generated by compiler ... exceeds the
# typical limit of 5000000"); `--internal-max-instruction-limit` lifts it. It is an internal option (not in neuronx-cc 2.27's
# `compile --help`); NxDI passes it for its MoE models (aws-neuron/neuronx-distributed-inference
# models/qwen3_moe/modeling_qwen3_moe.py, read by the upstream-harvest agent, 2026-10-05), and the farm compiled every
# 45-layer GLM-5.3-Flash prefill piece with it (q/pf-p8k45-3a39ec8, 25 of 25 graphs). A prefill piece of more than this many MoE
# layers gets PREFILL_BIG_LIMIT by default: GLM-5.3-Flash's 8192-token prefill as ONE 45-layer piece (2048 rows per
# DP-attention group) compiles under 30M (trn1, SDK 2.32, 2026-10-05, docs/neuron-notes.md "Collectives issued from an
# NKI kernel on trn1"). Only the prefill pieces take it, so every decode graph keeps its key.
PREFILL_DEFAULT_MOE_GROUP = 12
PREFILL_BIG_LIMIT = "--internal-max-instruction-limit=30000000"


def prefill_cc_args(ecfg) -> list[str]:
    """Extra neuronx-cc arguments for the piecewise prefill pieces only: KILN_PREFILL_CC_ARGS (split as KILN_CC_ARGS; "none"
    for nothing), else PREFILL_BIG_LIMIT when the prefill pieces hold more than PREFILL_DEFAULT_MOE_GROUP MoE layers."""
    env = os.environ.get("KILN_PREFILL_CC_ARGS")
